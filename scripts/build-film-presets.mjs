// Convert a folder of Camera Raw / Lightroom .xmp presets into the bundled
// "Film" preset set (src/lib/presets/filmPresets.data.js).
//   node scripts/build-film-presets.mjs <folder-with-xmp>
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { importCameraRawPreset } from "../src/lib/cameraRawPresets.js";

const sourceDir = process.argv[2];
if (!sourceDir) {
  console.error("Usage: node scripts/build-film-presets.mjs <folder-with-xmp>");
  process.exit(1);
}

const GROUPS = [
  { id: "film-kodak", label: "Film · Kodak", match: /kodak/i },
  { id: "film-fuji", label: "Film · Fuji", match: /fuji/i },
  { id: "film-agfa", label: "Film · Agfa", match: /agfa/i },
  { id: "film-ilford", label: "Film · Ilford", match: /ilford/i },
  { id: "film-instant", label: "Film · Instant", match: /polaroid|px-|time-zero|impossible/i },
  { id: "film-other", label: "Film · Other", match: /.*/ }
];

const slug = text => text.replace(/\+/g, " plus ").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const files = (await readdir(sourceDir)).filter(file => file.toLowerCase().endsWith(".xmp")).sort();
const presets = [];
const seen = new Set();
for (const file of files) {
  const preset = importCameraRawPreset(await readFile(path.join(sourceDir, file), "utf8"), file);
  const name = file.replace(/\.xmp$/i, "");
  // "TK - … (None)" toolkit files only reset a panel; they are not looks.
  if (/^TK - /i.test(name) || !Object.keys(preset.adjustments).length) continue;
  const key = JSON.stringify(preset.adjustments);
  if (seen.has(key)) continue;
  seen.add(key);
  const group = GROUPS.find(item => item.match.test(name));
  // Ids keep the original file name; the display name drops the "N - " prefix.
  presets.push({ id: `film_${slug(name)}`, name: name.replace(/^N - /, ""), group: group.id, adjustments: preset.adjustments, cameraRaw: preset.cameraRaw });
}

const groups = GROUPS.filter(group => presets.some(preset => preset.group === group.id)).map(({ id, label }) => ({ id, label }));
const out = `// Generated by scripts/build-film-presets.mjs — do not edit by hand.\nexport default ${JSON.stringify({ groups, presets })};\n`;
await writeFile("src/lib/presets/filmPresets.data.js", out);
console.log(`${presets.length} presets, ${groups.length} groups, ${(out.length / 1024).toFixed(0)} KB`);
